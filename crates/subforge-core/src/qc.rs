//! Quality control: CPS, line length, durations, overlaps, gaps... plus automatic fixes.

use crate::model::{Event, Subtitle};
use crate::text::{count_chars, cps, line_lengths, parse_tags, tokenize, CountOpts, Token};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct QcConfig {
    pub max_cps: f64,
    pub max_line_len: usize,
    pub max_lines: usize,
    pub min_duration_ms: i64,
    pub max_duration_ms: i64,
    /// Minimum gap between consecutive subtitles (0 = disabled).
    pub min_gap_ms: i64,
    pub count: CountOpts,
}

impl Default for QcConfig {
    fn default() -> Self {
        QcConfig {
            max_cps: 20.0,
            max_line_len: 42,
            max_lines: 2,
            min_duration_ms: 833,
            max_duration_ms: 7000,
            min_gap_ms: 83,
            count: CountOpts::default(),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, PartialOrd, Ord)]
#[serde(rename_all = "snake_case")]
pub enum Severity {
    Info,
    Warning,
    Error,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum IssueKind {
    InvalidTiming,
    Overlap,
    TooShort,
    TooLong,
    CpsTooHigh,
    LineTooLong,
    TooManyLines,
    GapTooSmall,
    Empty,
    UnbalancedTags,
    ExtraSpaces,
    UnknownStyle,
}

impl IssueKind {
    pub fn label(self) -> &'static str {
        match self {
            IssueKind::InvalidTiming => "Invalid timing",
            IssueKind::Overlap => "Overlap",
            IssueKind::TooShort => "Too short",
            IssueKind::TooLong => "Too long",
            IssueKind::CpsTooHigh => "CPS too high",
            IssueKind::LineTooLong => "Line too long",
            IssueKind::TooManyLines => "Too many lines",
            IssueKind::GapTooSmall => "Gap too small",
            IssueKind::Empty => "Empty",
            IssueKind::UnbalancedTags => "Unbalanced tags",
            IssueKind::ExtraSpaces => "Extra spaces",
            IssueKind::UnknownStyle => "Unknown style",
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Issue {
    /// 0-based event index
    pub index: usize,
    pub kind: IssueKind,
    pub severity: Severity,
    pub message: String,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, Default)]
pub struct EventStats {
    pub duration_ms: i64,
    pub chars: usize,
    pub cps: f64,
    pub lines: usize,
    pub max_line_len: usize,
}

pub fn stats(e: &Event, count: CountOpts) -> EventStats {
    let plain = e.plain();
    let ll = line_lengths(&plain);
    EventStats {
        duration_ms: e.duration(),
        chars: count_chars(&plain, count),
        cps: if plain.trim().is_empty() { 0.0 } else { cps(&plain, e.duration(), count) },
        lines: if plain.is_empty() { 0 } else { ll.len() },
        max_line_len: ll.into_iter().max().unwrap_or(0),
    }
}

/// Indices of non-comment events sorted by start time.
/// A frame generated by a frame-by-frame animation (checked through its source line instead).
fn is_frame(e: &Event) -> bool {
    e.effect.starts_with(crate::anim::EFFECT_GEN)
}
/// The (commented) source line of a frame-by-frame animation: it stands for the whole animation.
fn is_anim_source(e: &Event) -> bool {
    e.comment && e.effect.starts_with(crate::anim::EFFECT_SRC)
}
/// Lines that take part in QC: dialogue lines plus animation sources, minus generated frames.
fn checked(e: &Event) -> bool {
    (!e.comment || is_anim_source(e)) && !is_frame(e)
}

fn time_order(sub: &Subtitle) -> Vec<usize> {
    let mut v: Vec<usize> = (0..sub.events.len()).filter(|&i| checked(&sub.events[i])).collect();
    v.sort_by_key(|&i| (sub.events[i].start, sub.events[i].end));
    v
}

/// For each event, the index of the next event (same style) in time order.
fn next_same_style(sub: &Subtitle, order: &[usize]) -> Vec<Option<usize>> {
    let mut next = vec![None; sub.events.len()];
    for (k, &i) in order.iter().enumerate() {
        next[i] = order[k + 1..].iter().copied().find(|&j| sub.events[j].style == sub.events[i].style && sub.events[j].layer == sub.events[i].layer);
    }
    next
}

pub fn check(sub: &Subtitle, cfg: &QcConfig) -> Vec<Issue> {
    let mut issues = Vec::new();
    let mut push = |index, kind, severity, message: String| issues.push(Issue { index, kind, severity, message });
    let order = time_order(sub);
    let next = next_same_style(sub, &order);
    let has_styles = !sub.styles.is_empty();

    for (i, e) in sub.events.iter().enumerate() {
        if !checked(e) {
            continue;
        }
        let st = stats(e, cfg.count);
        let plain = e.plain();
        if e.end <= e.start {
            push(i, IssueKind::InvalidTiming, Severity::Error, format!("end ({}) is not after start ({})", e.end, e.start));
        } else {
            if st.duration_ms < cfg.min_duration_ms && !plain.trim().is_empty() {
                push(i, IssueKind::TooShort, Severity::Warning, format!("duration {} ms < {} ms", st.duration_ms, cfg.min_duration_ms));
            }
            if cfg.max_duration_ms > 0 && st.duration_ms > cfg.max_duration_ms {
                push(i, IssueKind::TooLong, Severity::Warning, format!("duration {} ms > {} ms", st.duration_ms, cfg.max_duration_ms));
            }
            if cfg.max_cps > 0.0 && st.cps > cfg.max_cps {
                let sev = if st.cps > cfg.max_cps * 1.25 { Severity::Error } else { Severity::Warning };
                push(i, IssueKind::CpsTooHigh, sev, format!("CPS {:.1} > {:.1}", st.cps, cfg.max_cps));
            }
        }
        if plain.trim().is_empty() && !e.text.contains("\\p") {
            push(i, IssueKind::Empty, Severity::Warning, "empty subtitle".into());
        }
        if cfg.max_line_len > 0 && st.max_line_len > cfg.max_line_len {
            push(i, IssueKind::LineTooLong, Severity::Warning, format!("line length {} > {}", st.max_line_len, cfg.max_line_len));
        }
        if cfg.max_lines > 0 && st.lines > cfg.max_lines {
            push(i, IssueKind::TooManyLines, Severity::Warning, format!("{} lines > {}", st.lines, cfg.max_lines));
        }
        if e.text.matches('{').count() != e.text.matches('}').count() || html_unbalanced(&e.text) {
            push(i, IssueKind::UnbalancedTags, Severity::Error, "unbalanced { } or formatting tags".into());
        }
        if plain.contains("  ") || plain.lines().any(|l| l != l.trim()) {
            push(i, IssueKind::ExtraSpaces, Severity::Info, "leading/trailing or double spaces".into());
        }
        if has_styles && sub.style(&e.style).is_none() {
            push(i, IssueKind::UnknownStyle, Severity::Warning, format!("style '{}' does not exist", e.style));
        }
        if let Some(j) = next[i] {
            let n = &sub.events[j];
            if n.start < e.end {
                push(i, IssueKind::Overlap, Severity::Error, format!("overlaps #{} by {} ms", j + 1, e.end - n.start));
            } else if cfg.min_gap_ms > 0 && n.start - e.end < cfg.min_gap_ms && n.start != e.end {
                push(i, IssueKind::GapTooSmall, Severity::Info, format!("gap to #{} is {} ms (< {} ms)", j + 1, n.start - e.end, cfg.min_gap_ms));
            }
        }
    }
    issues
}

/// Detect `{\i1}` without matching `{\i0}` is fine in ASS, so only check stray HTML tags left in text.
fn html_unbalanced(text: &str) -> bool {
    for t in ["i", "b", "u"] {
        let open = text.matches(&format!("<{t}>")).count();
        let close = text.matches(&format!("</{t}>")).count();
        if open != close {
            return true;
        }
    }
    false
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(default)]
pub struct FixOpts {
    pub trim_spaces: bool,
    pub remove_empty: bool,
    pub fix_invalid: bool,
    pub fix_overlaps: bool,
    pub enforce_min_gap: bool,
    pub extend_short: bool,
    pub extend_for_cps: bool,
    pub cap_long: bool,
    pub sort: bool,
    /// Break single lines longer than `max_line_len` into two balanced lines (word-aware for Thai).
    pub rebalance_long: bool,
}

impl Default for FixOpts {
    fn default() -> Self {
        FixOpts {
            trim_spaces: true,
            remove_empty: true,
            fix_invalid: true,
            fix_overlaps: true,
            enforce_min_gap: false,
            extend_short: true,
            extend_for_cps: true,
            cap_long: false,
            sort: true,
            rebalance_long: false,
        }
    }
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct FixReport {
    pub trimmed: usize,
    pub removed_empty: usize,
    pub fixed_invalid: usize,
    pub fixed_overlaps: usize,
    pub gaps_enforced: usize,
    pub extended: usize,
    pub capped: usize,
    pub rebalanced: usize,
}

impl FixReport {
    pub fn total(&self) -> usize {
        self.trimmed + self.removed_empty + self.fixed_invalid + self.fixed_overlaps + self.gaps_enforced + self.extended + self.capped + self.rebalanced
    }
}

fn trim_text(text: &str) -> String {
    // trim spaces around \N and collapse double spaces in text runs only
    let mut out = String::new();
    for tok in tokenize(text) {
        match tok {
            Token::Block(b) => {
                out.push('{');
                out.push_str(b);
                out.push('}');
            }
            Token::Text(t) => {
                let mut s = t.to_string();
                while s.contains("  ") {
                    s = s.replace("  ", " ");
                }
                s = s.replace(" \\N", "\\N").replace("\\N ", "\\N");
                out.push_str(&s);
            }
        }
    }
    // trim leading/trailing spaces of the whole text (outside blocks)
    let lead_blocks: String = {
        let mut lb = String::new();
        let mut rest = out.as_str();
        while rest.starts_with('{') {
            if let Some(j) = rest.find('}') {
                lb.push_str(&rest[..=j]);
                rest = &rest[j + 1..];
            } else {
                break;
            }
        }
        let trimmed = rest.trim_start().to_string();
        lb.push_str(&trimmed);
        lb
    };
    let mut r = lead_blocks.trim_end().to_string();
    while r.ends_with("\\N") {
        r.truncate(r.len() - 2);
        r = r.trim_end().to_string();
    }
    r
}

pub fn fix(sub: &mut Subtitle, cfg: &QcConfig, opts: &FixOpts) -> FixReport {
    let mut rep = FixReport::default();
    if opts.trim_spaces {
        for e in sub.events.iter_mut().filter(|e| !is_frame(e) && !is_anim_source(e)) {
            let t = trim_text(&e.text);
            if t != e.text {
                e.text = t;
                rep.trimmed += 1;
            }
        }
    }
    if opts.rebalance_long && cfg.max_line_len > 0 {
        for e in sub.events.iter_mut() {
            if e.comment || is_frame(e) || e.text.contains("\\N") {
                continue;
            }
            let plain = e.plain();
            if crate::text::grapheme_len(&plain) > cfg.max_line_len {
                let b = crate::text::balance_two_lines(&e.text);
                if b != e.text {
                    e.text = b;
                    rep.rebalanced += 1;
                }
            }
        }
    }
    if opts.remove_empty {
        let before = sub.events.len();
        sub.events.retain(|e| e.comment || !e.plain().trim().is_empty() || has_drawing(&e.text));
        rep.removed_empty = before - sub.events.len();
    }
    if opts.fix_invalid {
        for e in sub.events.iter_mut().filter(|e| !is_frame(e)) {
            if e.end <= e.start {
                e.end = e.start + cfg.min_duration_ms.max(500);
                rep.fixed_invalid += 1;
            }
        }
    }
    if opts.sort {
        sub.events.sort_by(|a, b| a.start.cmp(&b.start).then(a.end.cmp(&b.end)));
    }
    let gap = if opts.enforce_min_gap { cfg.min_gap_ms } else { 0 };

    // extension passes (never past next.start - gap)
    if opts.extend_short || opts.extend_for_cps || opts.cap_long {
        let order = time_order(sub);
        let next = next_same_style(sub, &order);
        for i in 0..sub.events.len() {
            if sub.events[i].comment || is_frame(&sub.events[i]) {
                continue;
            }
            let limit = next[i].map(|j| sub.events[j].start - gap).unwrap_or(i64::MAX);
            let e = &sub.events[i];
            let mut want = e.end;
            if opts.extend_short {
                want = want.max(e.start + cfg.min_duration_ms);
            }
            if opts.extend_for_cps && cfg.max_cps > 0.0 {
                let chars = count_chars(&e.plain(), cfg.count) as f64;
                let need = (chars / cfg.max_cps * 1000.0).ceil() as i64;
                want = want.max(e.start + need);
            }
            if opts.cap_long && cfg.max_duration_ms > 0 {
                want = want.min(e.start + cfg.max_duration_ms);
            }
            let new_end = if want > e.end { want.min(limit).max(e.end) } else { want };
            if new_end != e.end {
                if new_end > sub.events[i].end {
                    rep.extended += 1;
                } else {
                    rep.capped += 1;
                }
                sub.events[i].end = new_end;
            }
        }
    }
    if opts.fix_overlaps || opts.enforce_min_gap {
        let order = time_order(sub);
        let next = next_same_style(sub, &order);
        for i in 0..sub.events.len() {
            if is_anim_source(&sub.events[i]) {
                continue; // retime animations by moving their source line
            }
            let Some(j) = next[i] else { continue };
            let ns = sub.events[j].start;
            let e = &mut sub.events[i];
            if opts.fix_overlaps && e.end > ns {
                e.end = (ns - gap).max(e.start + 1);
                rep.fixed_overlaps += 1;
            } else if opts.enforce_min_gap && gap > 0 && ns - e.end < gap && ns > e.end {
                e.end = (ns - gap).max(e.start + 1);
                rep.gaps_enforced += 1;
            }
        }
    }
    rep
}

fn has_drawing(text: &str) -> bool {
    tokenize(text).iter().any(|t| matches!(t, Token::Block(b) if parse_tags(b).iter().any(|(n, a)| n == "p" && a.trim() != "0")))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn qc_and_fix() {
        let mut s = Subtitle::new();
        s.events.push(Event::new(0, 300, "This is a fairly long line of text"));
        s.events.push(Event::new(1000, 900, "bad"));
        s.events.push(Event::new(1500, 3000, "  "));
        let issues = check(&s, &QcConfig::default());
        assert!(issues.iter().any(|i| i.kind == IssueKind::CpsTooHigh && i.index == 0));
        assert!(issues.iter().any(|i| i.kind == IssueKind::InvalidTiming && i.index == 1));
        assert!(issues.iter().any(|i| i.kind == IssueKind::Empty && i.index == 2));
        let rep = fix(&mut s, &QcConfig::default(), &FixOpts::default());
        assert_eq!(rep.removed_empty, 1);
        assert_eq!(s.events.len(), 2);
        assert!(s.events[0].end <= s.events[1].start);
        assert!(s.events[1].end > s.events[1].start);
    }
    #[test]
    fn animations_checked_as_one_line() {
        let mut s = Subtitle::new();
        s.events.push(Event::new(0, 2000, "Sign text"));
        let mut tw = crate::anim::Tween { mode: crate::anim::Mode::FrameByFrame, ..Default::default() };
        tw.animate.pos = true;
        tw.from = crate::anim::State::of_event(&s, &s.events[0]);
        tw.to = tw.from;
        tw.to.x += 300.0;
        crate::anim::apply_tween(&mut s, 0, &tw, 24.0).unwrap();
        assert!(s.events.len() > 20);
        let issues = check(&s, &QcConfig::default());
        assert!(issues.is_empty(), "{issues:?}");
        let before = s.events.clone();
        fix(&mut s, &QcConfig::default(), &FixOpts::default());
        let gens = |v: &Vec<Event>| v.iter().filter(|e| is_frame(e)).map(|e| (e.start, e.end, e.text.clone())).collect::<Vec<_>>();
        assert_eq!(gens(&before), gens(&s.events));
    }
    #[test]
    fn trim() {
        assert_eq!(trim_text("{\\an8}  a  b \\N c "), "{\\an8}a b\\Nc");
    }
}
